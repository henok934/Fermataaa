function changeLanguage(langCode, langName) {
    const langElement = document.getElementById('currentLang');
    if (langElement) langElement.innerText = langName;
    
    localStorage.setItem('userLanguage', langCode);
    localStorage.setItem('userSelectedLangName', langName);
    
    const t = translations[langCode] || translations["en"];
    
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (t[key]) {
            el.innerHTML = t[key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (t[key]) {
            el.placeholder = t[key];
        }
    });
}

document.addEventListener("DOMContentLoaded", function() {
    const savedLang = localStorage.getItem("userLanguage") || "en";
    const savedName = localStorage.getItem('userSelectedLangName') || "English";
    if (translations[savedLang]) {
        changeLanguage(savedLang, savedName);
    }
});
